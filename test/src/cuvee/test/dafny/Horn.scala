package cuvee.test
package dafny

import utest._

import cuvee.Error
import cuvee.core._

// runs the examples with -chc against z3, which checks the clauses for satisfiability:
// sat if all queries hold, unsat if one of them fails,
// the expected result is given by the first line of each example as for Verify;
// the examples of vcgen are not covered, since their procedures with a body have contracts
object Horn extends TestSuite:
  // status reported for each expected result
  val expected = Map(
    "// expected: valid" -> Status.Sat,
    "// expected: invalid" -> Status.Unsat
  )

  val tests =
    Examples.tests(Examples.find(os.sub / "dafny" / "horn", "dfy")): file =>
      val first = os.read.lines(file).head
      assert(expected.contains(first))

      // the answer to the check-sat at the end is the last result
      val (_, results) = cuvee.Cuvee.run("-chc", "-z3", file.toString)
      results.collect { case error: Error => error.msg } ==> Nil
      Examples.status(results) ==> expected(first)

// the commands generated by -chc
object HornCmds extends TestSuite:
  def output(path: os.SubPath): List[Cmd] =
    val (cmds, errors) = Examples.output("-chc", "-print", "null", (Examples.root / path).toString)
    errors ==> Nil
    cmds

  val tests = Tests:
    // the logic is set at the beginning, every procedure with a body has predicates for its pre- and postcondition,
    // and the clauses are checked at the end of the input
    test("max.dfy"):
      val cmds = output(os.sub / "dafny" / "horn" / "max.dfy")
      cmds.head ==> SetLogic("HORN")
      val names = cmds.collect { case DeclareFun(fun, _) => fun.name.name }
      assert(names.contains("max_pre"), names.contains("max_post"))
      cmds.takeRight(2) ==> List(CheckSat, GetModel)

    // a given logic is replaced, not duplicated
    test("logic replaced"):
      val cmds = output(os.sub / "smtlib" / "basic.smt2")
      cmds.collect { case cmd: SetLogic => cmd } ==> List(SetLogic("HORN"))

    // the model of the predicates is read back from the solver and printed in the language of the input
    test("model"):
      val max = Examples.root / "dafny" / "horn" / "max.dfy"
      val (_, results) = cuvee.Cuvee.run("-chc", "-z3", max.toString)
      val List(Status.Sat, Model(decls)) = results.filterNot(_ == Ack.Success): @unchecked
      assert(decls.nonEmpty && decls.forall(_.isInstanceOf[DefineFun]))
      assert(cuvee.dafny.Printer.lines(Model(decls)).exists(_.startsWith("function max_")))

    // no model if the clauses are unsatisfiable
    test("no model"):
      val invalid = Examples.root / "dafny" / "horn" / "invalid_max.dfy"
      val (_, results) = cuvee.Cuvee.run("-chc", "-z3", invalid.toString)
      results.filterNot(_ == Ack.Success) ==> List(Status.Unsat)

    // procedures without body have no predicates, their contracts are instantiated at the calls,
    // such that no predicate is polymorphic
    test("contract.dfy"):
      val cmds = output(os.sub / "dafny" / "horn" / "contract.dfy")
      val preds = cmds.collect { case DeclareFun(fun, _) if fun.res == Sort.bool => fun }
      val names = preds.map(_.name.name)
      assert(names.contains("main_pre"), !names.exists(_.startsWith("swap_")))
      assert(preds.forall(_.params.isEmpty))

    // the predicates of procedures with a body replace their contracts
    test("contracts"):
      Examples.check("dfy", "method f(x: int) returns (y: int) ensures y == x { y := x; }", "-chc") ==>
        List("procedure with body has a contract")

    // the entry points are the procedures that are not called
    test("entry points"):
      val text = "method f(x: int) returns (y: int) { y := x; }\nmethod g(x: int) returns (y: int) { y := f(x); }\n"
      val (cmds, errors) = Examples.output("-chc", "-print", "null", os.temp(text, suffix = ".dfy").toString)
      errors ==> Nil
      val entries = cmds.collect { case Assert(_, _, All(_, Imp(True, App(fun, _, _, _))), _) => fun.name.name }
      entries ==> List("g_pre")
