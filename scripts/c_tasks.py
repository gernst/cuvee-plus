#!/usr/bin/env python3
"""Task definitions of the C versions of the local SV-COMP benchmarks, for BenchExec.

The C programs in benchmarks/sv-comp/c are printed from the Dafny translations in
benchmarks/sv-comp/dafny, so each task takes its expected verdict from the Dafny task definition,
and its data model (ILP32 or LP64) from the original task in sv-benchmarks. A definition is written
for every Dafny task, also where the C program is not there yet, and c.set takes all of them. Until the
missing programs are added, BenchExec rejects the benchmark definitions that include c.set (all their
run definitions), since a task lacks its input file; --check lists the missing programs.
"""

import argparse
import shutil
import sys
from pathlib import Path

import yaml

import common

ROOT = common.SCRIPTS.parent
DAFNY = ROOT / "benchmarks" / "sv-comp" / "dafny"
C = ROOT / "benchmarks" / "sv-comp" / "c"
SV_BENCHMARKS = ROOT / "sv-benchmarks" / "c"

PROPERTY = "unreach-call.prp"

SET = """# the task definitions of the C versions of the local SV-COMP benchmarks, for BenchExec, relative to this
# file, with the expected verdicts of the property unreach-call; generated by scripts/c_tasks.py from those
# of the Dafny translations in ../dafny
*/*.yml
"""

TASK = """format_version: '2.0'

# the C version of the SV-COMP task {task}, printed from ../../dafny/{task_dfy}
input_files: '{name}.c'

properties:
  - property_file: ../properties/{property}
    expected_verdict: {verdict}

options:
  language: C
  data_model: {data_model}
"""


def verdict(definition: Path) -> bool:
    """The expected verdict of unreach-call in a task definition."""
    content = yaml.safe_load(definition.read_text())
    for entry in content.get("properties", []):
        if entry.get("property_file", "").endswith(PROPERTY) and "expected_verdict" in entry:
            return bool(entry["expected_verdict"])
    raise ValueError(f"no expected verdict of {PROPERTY} in {definition}")


def data_model(original: Path) -> str:
    # tasks without an original (none so far) default to the data model of most of SV-COMP
    if not original.exists():
        print(f"no original task {original}, assuming ILP32", file=sys.stderr)
        return "ILP32"
    return yaml.safe_load(original.read_text()).get("options", {}).get("data_model", "ILP32")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only report which C programs are missing")
    args = parser.parse_args()

    definitions = sorted(DAFNY.glob("*/*.yml"))
    missing = [definition for definition in definitions if not (C / definition.parent.name / f"{definition.stem}.c").exists()]
    if not args.check:
        (C / "properties").mkdir(parents=True, exist_ok=True)
        shutil.copyfile(SV_BENCHMARKS / "properties" / PROPERTY, C / "properties" / PROPERTY)
        (C / "c.set").write_text(SET)
        for definition in definitions:
            folder = definition.parent.name
            task = f"{folder}/{definition.stem}.yml"
            target = C / folder / f"{definition.stem}.yml"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(
                TASK.format(
                    task=task,
                    task_dfy=f"{folder}/{definition.stem}.dfy",
                    name=definition.stem,
                    property=PROPERTY,
                    verdict=str(verdict(definition)).lower(),
                    data_model=data_model(SV_BENCHMARKS / task),
                )
            )
        print(f"{len(definitions)} task definitions in {C}")
    print(f"{len(missing)} C programs missing", file=sys.stderr)
    for definition in missing:
        print(f"  {definition.parent.name}/{definition.stem}.c", file=sys.stderr)


if __name__ == "__main__":
    main()
